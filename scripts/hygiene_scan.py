"""Repository hygiene scan (criterion 13). Exit 0 clean, 1 match, 2 error."""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

# Kept only here per PLAN; do not duplicate in tracked docs.
DEFAULT_PATTERN = (
    r"openai|anthropic|chatgpt|gpt-4|gpt-5|cursor|copilot|claude|"
    r"Co-authored-by|Generated by|"
    r"[\u2014\u2013\u2212]|"
    r"/home/ubuntu|/Users/|/workspace/|/tmp/"
)

EXCLUDE_RE = re.compile(
    r"^\.github/workflows/ci\.yml$|"
    r"package-lock\.json$|"
    r"\.png$|^LICENSE$|"
    r"tests/fixtures/hygiene_trap\.txt$"
)


def tracked_files(repo_root: Path) -> list[str]:
    out = subprocess.check_output(["git", "ls-files"], cwd=repo_root, text=True)
    files: list[str] = []
    for line in out.splitlines():
        if line and not EXCLUDE_RE.search(line):
            files.append(line)
    return files


def scan_paths(repo_root: Path, paths: list[str], pattern: str) -> int:
    if not paths:
        return 0
    cmd = ["git", "grep", "-P", "-n", pattern, "--"]
    cmd.extend(paths)
    proc = subprocess.run(cmd, cwd=repo_root, text=True, capture_output=True)
    if proc.returncode == 0:
        sys.stdout.write(proc.stdout)
        return 1
    if proc.returncode == 1:
        return 0
    sys.stderr.write(proc.stderr or f"git grep failed ({proc.returncode})\n")
    return 2


def main() -> None:
    repo = Path(".").resolve()
    if len(sys.argv) >= 2 and sys.argv[1] == "--trap":
        rc = scan_paths(repo, ["tests/fixtures/hygiene_trap.txt"], DEFAULT_PATTERN)
        raise SystemExit(1 if rc == 1 else 2)
    pattern = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PATTERN
    files = tracked_files(repo)
    rc = scan_paths(repo, files, pattern)
    raise SystemExit(rc)


if __name__ == "__main__":
    main()
